CREATE TABLE IF NOT EXISTS spieler (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  name_lc TEXT NOT NULL UNIQUE,
  token_hash TEXT NOT NULL,
  erstellt INTEGER NOT NULL,
  zuletzt INTEGER NOT NULL,
  hof TEXT,
  hof_t INTEGER
);
CREATE TABLE IF NOT EXISTS hilfe (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  an INTEGER NOT NULL,
  von_id INTEGER NOT NULL,
  von TEXT NOT NULL,
  idx INTEGER NOT NULL,
  t INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS hilfe_an ON hilfe(an);
CREATE INDEX IF NOT EXISTS hilfe_paar ON hilfe(von_id, an, t);
CREATE TABLE IF NOT EXISTS angebote (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  von INTEGER NOT NULL,
  gibt TEXT NOT NULL,
  will TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'offen',
  t INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS angebote_status ON angebote(status, t);
CREATE TABLE IF NOT EXISTS post (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  an INTEGER NOT NULL,
  art TEXT NOT NULL,
  inhalt TEXT NOT NULL,
  t INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS post_an ON post(an);
